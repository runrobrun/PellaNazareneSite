<h2 class="wp-block-heading">Statement of beliefs</h2>
<!-- /wp:heading -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Trinity</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We believe in one God: the Father, Son, and Holy Spirit.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Scripture</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We believe that the Old and New Testament Scriptures, given by plenary inspiration, contain all truth necessary to faith and Christian living.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Sinful nature</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We believe that human beings are born with a fallen nature, and are, therefore, inclined to evil, and that continually.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Eternity</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We believe that the finally impenitent are hopelessly and eternally lost.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Salvation</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We believe that the atonement through Jesus Christ is for the whole human race; and that whosoever repents and believes on the Lord Jesus Christ is justified and regenerated and saved from the dominion of sin.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Sanctification</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We believe that believers are to be sanctified wholly, subsequent to regeneration, through faith in the Lord Jesus Christ.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">The Holy Spirit</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We believe that the Holy Spirit bears witness to the new birth, and also to the entire sanctification of believers.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Christ’s return</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We believe that our Lord will return, the dead will be raised, and the final judgment will take place.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Our Nazarene heritage</h2>
<!-- /wp:heading -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">A Christian people</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>As members of the Church Universal, we join with all true believers in proclaiming the Lordship of Jesus Christ and in affirming the historic Trinitarian creeds and beliefs of the Christian faith. We value our Wesleyan-Holiness heritage and believe it to be a way of understanding the faith that is true to Scripture, reason, tradition, and experience.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>We are united with all believers in proclaiming the Lordship of Jesus Christ. We believe that in divine love God offers to all people forgiveness of sins and restored relationship. In being reconciled to God, we believe that we are also to be reconciled to one another, loving each other as we have been loved by God and forgiving each other as we have been forgiven by God. We believe that our life together is to exemplify the character of Christ. We look to Scripture as the primary source of spiritual truth confirmed by reason, tradition, and experience.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Jesus Christ is the Lord of the Church, which, as the Nicene Creed tells us, is one, holy, universal, and apostolic. In Jesus Christ and through the Holy Spirit, God the Father offers forgiveness of sin and reconciliation to all the world. Those who respond to God’s offer in faith become the people of God. Having been forgiven and reconciled in Christ, we forgive and are reconciled to one another. In this way, we are Christ’s Church and Body and reveal the unity of that Body. As the one Body of Christ, we have “one Lord, one faith, one baptism.” We affirm the unity of Christ’s Church and strive in all things to preserve it (Ephesians 4:5, 3).</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">A holiness people</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>God, who is holy, calls us to a life of holiness. We believe that the Holy Spirit seeks to do in us a second work of grace, called by various terms including “entire sanctification” and “baptism with the Holy Spirit,” cleansing us from all sin, renewing us in the image of God, empowering us to love God with our whole heart, soul, mind, and strength, and our neighbors as ourselves, and producing in us the character of Christ. Holiness in the life of believers is most clearly understood as Christlikeness.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Because we are called by Scripture and drawn by grace to worship God and to love Him with our whole heart, soul, mind, and strength, and our neighbors as ourselves, we commit ourselves fully and completely to God, believing that we can be “sanctified wholly,” as a second crisis experience. We believe that the Holy Spirit convicts, cleanses, fills, and empowers us as the grace of God transforms us day by day into a people of love, spiritual discipline, ethical and moral purity, compassion, and justice. It is the work of the Holy Spirit that restores us in the image of God and produces in us the character of Christ.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>We believe in God the Father, the Creator, who calls into being what does not exist. We once were not, but God called us into being, made us for himself, and fashioned us in His own image. We have been commissioned to bear the image of God: “I am the LORD . . . your God; therefore be holy, because I am holy.”</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">A missional people</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We are a sent people, responding to the call of Christ and empowered by the Holy Spirit to go into all the world, witnessing to the Lordship of Christ and participating with God in the building of the Church and the extension of His kingdom (Matthew 28:19-20; 2 Corinthians 6:1).</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Our mission begins in worship, ministers to the world in evangelism and compassion, encourages believers toward Christian maturity through discipleship, and prepares women and men for Christian service through Christian higher education.</p>
