<h2 class="wp-block-heading">Counting visits (Google Analytics)</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>On our live website we use Google Analytics to see, in totals, which pages people read and what kind of device they use, so we can make the site more helpful. It records things like the page you viewed, your type of browser, and roughly where you are (a city, not an address). Google Analytics does not keep your full internet address. It sets small files called cookies to tell visits apart.</p>
<!-- /wp:paragraph -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>We do not use it for advertising, and we do not sell this information.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>We do not count visits from our own staff when they are signed in.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>You can opt out.</strong> If your browser sends a “Global Privacy Control” or “Do Not Track” signal (a setting in Firefox, Brave, DuckDuckGo and others), our site does not load Google Analytics at all. You can also install Google’s <a href="https://tools.google.com/dlpage/gaoptout">opt-out browser add-on</a>.</li>
<!-- /wp:list-item --></ul>
